"""Render TDSE-Z VTK exports with ParaView (pvpython): images and movies.

``render`` writes a small pvpython script next to the output and runs it with
ParaView's ``pvpython`` (found on PATH, in ``$PARAVIEW_HOME/bin`` or in
``/Applications/ParaView*.app``). The script is kept, so the scene can be
opened and tuned in the ParaView GUI (``File > Load State`` is not needed:
run it with ``pvpython`` or paste it into the Python shell).

* 2D: log10 of the density as a colour map over ``decades`` decades, the
  potential as contour lines, time and field in the corner.
* 3D: volume rendering of log10 density plus density isosurfaces (fractions
  of the maximum), optional camera orbit.

A ``.pvd`` series gives one PNG per snapshot and, with ffmpeg on PATH, an MP4.
"""

from __future__ import annotations

import glob
import os
import shutil
import subprocess
from pathlib import Path
from typing import Optional, Sequence, Union

PathLike = Union[str, Path]


def find_pvpython(explicit: Optional[str] = None) -> str:
    """Locate ParaView's pvpython."""
    cands = [explicit, os.environ.get("PVPYTHON"), shutil.which("pvpython")]
    home = os.environ.get("PARAVIEW_HOME")
    if home:
        cands.append(str(Path(home) / "bin" / "pvpython"))
    cands += sorted(glob.glob("/Applications/ParaView*.app/Contents/bin/pvpython"), reverse=True)
    cands += sorted(glob.glob("/opt/ParaView*/bin/pvpython"), reverse=True)
    for c in cands:
        if c and Path(c).is_file() and os.access(c, os.X_OK):
            return c
    raise FileNotFoundError("pvpython not found: install ParaView, put pvpython on PATH or set PVPYTHON")


_SCRIPT = r'''
# generated by zkit.viz.paraview.render -- run with pvpython
from paraview.simple import *
import os
src_path = {src!r}
out_png = {png!r}
dim = {dim}
decades = {decades}
size = {size!r}
orbit = {orbit}
iso = {iso!r}

reader = OpenDataFile(src_path)
reader.UpdatePipelineInformation()
times = list(reader.TimestepValues) if hasattr(reader, "TimestepValues") and reader.TimestepValues else [0.0]
view = GetActiveViewOrCreate("RenderView")
view.ViewSize = size
view.OrientationAxesVisibility = 0
view.Background = [0.04, 0.04, 0.06]
try:
    view.UseColorPaletteForBackground = 0
except AttributeError:
    pass
scene = GetAnimationScene()
scene.UpdateAnimationUsingDataTimeSteps()

# fixed colour range over the series: log10 density, `decades` below the global max
top = -1e300
for t in times:
    reader.UpdatePipeline(t)
    r = reader.PointData["log10_density"].GetRange()
    top = max(top, r[1])
lo = top - decades

disp = Show(reader, view)
ColorBy(disp, ("POINTS", "log10_density"))
lut = GetColorTransferFunction("log10_density")
lut.ApplyPreset("Inferno (matplotlib)", True)
lut.AutomaticRescaleRangeMode = "Never"
lut.RescaleTransferFunction(lo, top)
pwf = GetOpacityTransferFunction("log10_density")
pwf.RescaleTransferFunction(lo, top)

if dim <= 2:
    disp.Representation = "Slice"
    if "potential" in reader.PointData.keys():
        pr = reader.PointData["potential"].GetRange()
        cont = Contour(Input=reader)
        cont.ContourBy = ["POINTS", "potential"]
        vmin = pr[0]
        cont.Isosurfaces = [vmin * f for f in (0.8, 0.6, 0.4, 0.2, 0.1, 0.05)]
        cd = Show(cont, view)
        ColorBy(cd, None)
        cd.AmbientColor = cd.DiffuseColor = [0.85, 0.85, 0.85]
        cd.Opacity = 0.35
        cd.LineWidth = 1.0
    view.InteractionMode = "2D"
    ResetCamera(view)
    view.CameraParallelProjection = 1
else:
    disp.Representation = "Volume"
    pwf.Points = [lo, 0.0, 0.5, 0.0, lo + 0.45 * decades, 0.01, 0.5, 0.0,
                  lo + 0.8 * decades, 0.2, 0.5, 0.0, top, 0.85, 0.5, 0.0]
    colours = [[1.0, 0.97, 0.75], [0.98, 0.55, 0.18], [0.62, 0.22, 0.65], [0.25, 0.35, 0.85]]
    alphas = [0.55, 0.3, 0.16, 0.08]
    for j, d in enumerate(iso):
        cont = Contour(Input=reader)
        cont.ContourBy = ["POINTS", "log10_density"]
        cont.Isosurfaces = [top - d]
        cd = Show(cont, view)
        ColorBy(cd, None)
        cd.AmbientColor = cd.DiffuseColor = colours[j % len(colours)]
        cd.Opacity = alphas[j % len(alphas)]
        cd.Specular = 0.4
    view.CameraPosition = [1.0, -1.6, 1.1]
    view.CameraFocalPoint = [0.0, 0.0, 0.0]
    view.CameraViewUp = [0.0, 0.0, 1.0]
    ResetCamera(view)
    view.GetActiveCamera().Dolly(1.12)

bar = GetScalarBar(lut, view)
bar.Title = "log10 density"
bar.ComponentTitle = ""
bar.HorizontalTitle = 1
bar.RangeLabelFormat = "%-#6.1f"
bar.TitleColor = bar.LabelColor = [0.9, 0.9, 0.9]
bar.Visibility = 1
bar.WindowLocation = "Any Location"
bar.Position = [0.84, 0.08]
bar.ScalarBarLength = 0.35

ann = PythonAnnotation(Input=reader)
ann.ArrayAssociation = "Field Data"
ann.Expression = {label!r}
ad = Show(ann, view)
ad.FontSize = 18
ad.Color = [0.95, 0.95, 0.95]
ad.WindowLocation = "Upper Left Corner"

grid = view.AxesGrid
grid.Visibility = 1
grid.XTitle, grid.YTitle, grid.ZTitle = "x (a.u.)", "y (a.u.)", "z (a.u.)"
for a in ("XTitleColor", "YTitleColor", "ZTitleColor", "XLabelColor", "YLabelColor", "ZLabelColor", "GridColor"):
    setattr(grid, a, [0.8, 0.8, 0.8])
grid.XTitleFontSize = grid.YTitleFontSize = grid.ZTitleFontSize = 16
if dim <= 2:
    grid.ShowGrid = 0
    view.CameraParallelScale *= 1.08

cam = view.GetActiveCamera()
step = 360.0 / max(1, len(times)) if orbit else 0.0
os.makedirs(os.path.dirname(out_png) or ".", exist_ok=True)
for k, t in enumerate(times):
    view.ViewTime = t
    scene.AnimationTime = t
    if step:
        cam.Azimuth(step)
    name = out_png if len(times) == 1 else out_png.replace(".png", "_%05d.png" % k)
    SaveScreenshot(name, view, ImageResolution=size, TransparentBackground=0)
print("frames", len(times))
'''


def render(
    source: PathLike,
    out: Optional[PathLike] = None,
    decades: float = 6.0,
    size: Sequence[int] = (1280, 1024),
    movie: bool = True,
    fps: int = 15,
    orbit: bool = False,
    iso: Sequence[float] = (1.0, 2.5, 4.0),
    pvpython: Optional[str] = None,
) -> Path:
    """Render a ``.vti`` (image) or ``.pvd``/``.visit`` series (frames + MP4).

    ``out`` is the PNG name (series: ``<out>_<k>.png``) or the ``.mp4``;
    default next to ``source``. ``iso`` are isosurface levels in decades
    below the maximum (3D). Returns the image or movie path.
    """
    source = Path(source).resolve()
    if source.suffix == ".visit":  # ParaView reads the .pvd written alongside
        source = source.with_suffix(".pvd")
    dim = _dimension(source)
    stem = source.with_suffix("")
    out = Path(out).resolve() if out else None
    mp4 = out if out and out.suffix == ".mp4" else (stem.parent / (stem.name + ".mp4"))
    png = out if out and out.suffix == ".png" else (stem.parent / "frames" / (stem.name + ".png"))
    script = png.parent / (stem.name + "_render.py")
    png.parent.mkdir(parents=True, exist_ok=True)
    script.write_text(_SCRIPT.format(src=str(source), png=str(png), dim=dim, decades=float(decades),
                                     size=list(size), orbit=bool(orbit), iso=list(iso), label=_label(source, dim)))
    r = subprocess.run([find_pvpython(pvpython), str(script)], capture_output=True, text=True)
    if r.returncode:
        raise RuntimeError(f"pvpython failed ({script}):\n{r.stdout[-2000:]}\n{r.stderr[-2000:]}")
    frames = sorted(png.parent.glob(png.stem + "_*.png"))
    if not frames:
        return png
    if movie and shutil.which("ffmpeg"):
        mp4.parent.mkdir(parents=True, exist_ok=True)
        subprocess.run(["ffmpeg", "-y", "-loglevel", "error", "-framerate", str(fps),
                        "-i", str(png.parent / (png.stem + "_%05d.png")),
                        "-vf", "pad=ceil(iw/2)*2:ceil(ih/2)*2", "-c:v", "libx264", "-pix_fmt", "yuv420p",
                        "-crf", "18", str(mp4)], check=True)
        return mp4
    return frames[0].parent


def _first_file(source: Path) -> Path:
    import re

    if source.suffix == ".pvd":
        return source.parent / re.search(r'file="([^"]+)"', source.read_text()).group(1)
    return source


def _label(source: Path, dim: int) -> str:
    """PythonAnnotation expression for the field data present in the files."""
    head = _first_file(source).open().read(3000)
    if 'Name="TIME"' not in head:
        if 'Name="ENERGY"' in head:
            return "'state %d,  E = %.6f a.u.' % (STATE[0], ENERGY[0])"
        return "''"
    if 'Name="E_x"' in head:
        comps = ", ".join(f"E_{c}[0]" for c in "xyz"[: max(dim, 1)])
        fmt = ", ".join(["%+.3f"] * max(dim, 1))
        return f"'t = %7.2f a.u.    E = ({fmt}) a.u.' % (TIME[0], {comps})"
    return "'t = %7.2f a.u.' % TIME[0]"


def _dimension(source: Path) -> int:
    """Spatial dimension of a .vti (or the first file of a .pvd): extents > 1."""
    import re

    head = _first_file(source).open().read(2000)
    ext = [int(v) for v in re.search(r'WholeExtent="([^"]+)"', head).group(1).split()]
    return sum(1 for a in range(3) if ext[2 * a + 1] > 0)


__all__ = ["find_pvpython", "render"]
